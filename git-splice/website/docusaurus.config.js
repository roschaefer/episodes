const {themes} = require('prism-react-renderer');

// The site renders the repository's own Markdown -- the README, walkthrough,
// concepts, scenarios, comparisons and design notes -- in place, so the pages are the
// same files `just docs-check` runs against real output.
const repoUrl = 'https://github.com/roschaefer/git-splice';
const siteUrl = 'https://roschaefer.github.io';
const baseUrl = '/git-splice/';
const repoFileLinks = require('./src/remark/repo-file-links');
const siteLinks = require('./src/remark/site-links');
const indexFirst = require('./src/index-first');

/** @type {import('@docusaurus/types').Config} */
module.exports = {
  title: 'git-splice',
  tagline: 'Keep folders of your monorepo in sync with their own repositories',
  url: siteUrl,
  baseUrl,
  organizationName: 'roschaefer',
  projectName: 'git-splice',
  trailingSlash: true,
  onBrokenLinks: 'throw',
  onBrokenAnchors: 'throw',
  markdown: {
    // CommonMark for .md files, so the HTML comments around scrut's hidden
    // setup blocks stay comments instead of failing as MDX.
    format: 'detect',
    hooks: {onBrokenMarkdownLinks: 'throw'},
  },

  presets: [
    [
      'classic',
      /** @type {import('@docusaurus/preset-classic').Options} */
      ({
        docs: {
          path: '..',
          include: [
            'README.md',
            'CONTRIBUTING.md',
            'docs/**/*.md',
            'test/walkthrough/**/*.md',
            'test/scenarios/**/*.md',
            'test/concepts/**/*.md',
            'test/comparisons/**/*.md',
          ],
          routeBasePath: '/',
          sidebarPath: require.resolve('./sidebars.js'),
          // A folder's README is its category's page, but the top folder of
          // an autogenerated list has no category: sidebars.js lists that
          // README in the category around the list instead.
          sidebarItemsGenerator: async ({defaultSidebarItemsGenerator, ...args}) =>
            indexFirst(
              (await defaultSidebarItemsGenerator(args)).filter(
                (item) => item.type !== 'doc' || item.id !== `${args.item.dirName}/README`,
              ),
            ),
          // docPath is relative to the repository root (path above); the
          // string form would put "../" after main/ and leave the branch.
          editUrl: ({docPath}) => `${repoUrl}/edit/main/${docPath}`,
          beforeDefaultRemarkPlugins: [
            [repoFileLinks, {repoUrl, repoRoot: require('path').resolve(__dirname, '..')}],
            [siteLinks, {siteUrl: siteUrl + baseUrl}],
          ],
        },
        blog: false,
        theme: {customCss: require.resolve('./src/css/custom.css')},
      }),
    ],
  ],

  // Full-text search, indexed at build time: no external service.
  themes: [
    [
      require.resolve('@easyops-cn/docusaurus-search-local'),
      {
        docsDir: '..',
        docsRouteBasePath: '/',
        indexBlog: false,
        hashed: true,
        language: ['en'],
        highlightSearchTermsOnTargetPage: true,
      },
    ],
  ],

  themeConfig:
    /** @type {import('@docusaurus/preset-classic').ThemeConfig} */
    ({
      navbar: {
        title: 'git-splice',
        items: [
          {type: 'docSidebar', sidebarId: 'docs', position: 'left', label: 'Docs'},
          {href: repoUrl, label: 'GitHub', position: 'right'},
        ],
      },
      footer: {
        style: 'dark',
        copyright: `MIT licensed · <a href="${repoUrl}">${repoUrl.replace('https://', '')}</a>`,
      },
      prism: {
        theme: themes.github,
        darkTheme: themes.dracula,
      },
    }),
};
